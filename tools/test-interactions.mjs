// DOM-only regression tests (happy-dom). Not a layout renderer; layout is checked with Playwright separately.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
const script = fs.readFileSync(path.join(root, 'public/assets/site.js'), 'utf8');
const checks = [];
const plain = new Window(); plain.document.write(html);
assert.equal(plain.document.querySelectorAll('[data-course-card]').length, 5);
assert.deepEqual([...plain.document.querySelectorAll('.course-card h3')].slice(0, 4).map(h => h.textContent), ['Data Analytics', 'Performance Marketing & Analytics', 'Web & App Development (Full Stack)', 'Tally with US GAAP & IFRS']);
checks.push('No-JS source: 5 course cards in owner order, all content present.');
const w = new Window({ url: 'http://localhost:8794/' });
w.matchMedia = q => ({ matches: q.includes('reduce'), media: q, addEventListener() {}, removeEventListener() {} });
w.IntersectionObserver = class { constructor(cb) { this.cb = cb } observe(t) { this.cb([{ target: t, isIntersecting: true }]) } unobserve() {} disconnect() {} };
let posted = null;
w.fetch = async (url, opts) => { posted = { url, body: JSON.parse(opts.body) }; return { ok: true, json: async () => ({ ok: true, id: 1 }) }; };
const d = w.document; d.write(html); w.eval(script);
assert.equal(d.querySelectorAll('[data-rv]:not(.in)').length, 0, 'reduced motion: all reveals visible');
const btn = d.querySelector('[data-menu]'); btn.click(); assert.equal(btn.getAttribute('aria-expanded'), 'true');
d.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); assert.equal(btn.getAttribute('aria-expanded'), 'false');
checks.push('Mobile menu opens and closes on Escape; reveals always visible with reduced motion.');
const form = d.querySelector('[data-enquiry-form]');
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(form.querySelector('[data-form-error]').hidden, false); assert.equal(posted, null);
form.elements.name.value = 'Riya Sharma'; form.elements.phone.value = '98765 43210';
form.elements.course.value = 'Data Analytics'; form.elements.preferred_time.value = 'Weekend';
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(posted, null, 'consent required before POST');
form.elements.consent.checked = true;
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
await new Promise(r => setTimeout(r, 50));
assert.equal(posted.url, '/api/enquiry');
for (const k of ['name', 'phone', 'course', 'preferred_time', 'level', 'message', 'website', 'source_page']) assert(k in posted.body, k);
assert.equal(form.querySelector('[data-form-status]').hidden, false);
checks.push('Enquiry form: client validation, JSON POST to /api/enquiry with worker field names, success state.');
const courseHtml = fs.readFileSync(path.join(root, 'public/courses/data-analytics/index.html'), 'utf8');
const gw = new Window({ url: 'http://localhost:8794/courses/data-analytics/' });
gw.matchMedia = q => ({ matches: q.includes('reduce'), media: q, addEventListener() {}, removeEventListener() {} });
gw.IntersectionObserver = class { constructor(cb) { this.cb = cb } observe(t) { this.cb([{ target: t, isIntersecting: true }]) } unobserve() {} disconnect() {} };
let guidePosted = null;
const clicks = [];
gw.fetch = async (url, opts) => { guidePosted = { url, body: JSON.parse(opts.body) }; return { ok: true, json: async () => ({ ok: true, id: 7, guide_url: '/guides/data-analytics.pdf' }) }; };
gw.HTMLAnchorElement.prototype.click = function click() { clicks.push(this.getAttribute('href')); };
const gd = gw.document; gd.write(courseHtml); gw.eval(script);
const gform = gd.querySelector('[data-guide-form]');
assert(gform, 'guide form present');
assert.equal(gd.querySelectorAll('[data-enquiry-form]').length, 1);
gform.elements.name.value = 'Riya Sharma';
gform.elements.phone.value = '98765 43210';
gform.dispatchEvent(new gw.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(guidePosted, null, 'guide consent required');
gform.elements.consent.checked = true;
gform.dispatchEvent(new gw.Event('submit', { bubbles: true, cancelable: true }));
await new Promise(r => setTimeout(r, 50));
assert.equal(guidePosted.url, '/api/enquiry');
assert.equal(guidePosted.body.source_page, 'guide:data-analytics');
assert.equal(guidePosted.body.course, 'Data Analytics');
assert.equal(guidePosted.body.preferred_time, 'Any time, please call me');
assert('website' in guidePosted.body);
assert.equal(gform.querySelector('[data-form-status]').hidden, false);
assert(clicks.includes('/guides/data-analytics.pdf'), clicks);
checks.push('Guide form: name, 10-digit phone, consent, honeypot; POST guide:<slug>; thank-you and PDF download.');
fs.writeFileSync(path.join(root, 'INTERACTION-TESTS.txt'), checks.map(c => 'PASS ' + c).join('\n') + '\n');
console.log(checks.map(c => 'PASS ' + c).join('\n'));
